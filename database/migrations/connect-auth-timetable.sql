-- Apply to the existing PostgreSQL timetable database before using Hibernate validate.
BEGIN;

-- Some installations already applied the authentication branch's role PK rename.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'role' AND column_name = 'id')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_schema = current_schema() AND table_name = 'role' AND column_name = 'role_id') THEN
        ALTER TABLE role RENAME COLUMN id TO role_id;
    END IF;
END
$$;

ALTER TABLE role ADD COLUMN IF NOT EXISTS created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL;

CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(150) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    enabled boolean NOT NULL,
    account_non_locked boolean NOT NULL,
    must_change_password boolean NOT NULL,
    lecturer_id bigint,
    student_id bigint,
    created_at timestamp NOT NULL,
    updated_at timestamp
);
CREATE INDEX IF NOT EXISTS idx_users_email ON users (email);
CREATE INDEX IF NOT EXISTS idx_users_enabled ON users (enabled);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id bigint NOT NULL REFERENCES users (id),
    role_id bigint NOT NULL REFERENCES role (role_id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    token_hash varchar(255) NOT NULL UNIQUE,
    expires_at timestamp NOT NULL,
    used boolean NOT NULL,
    created_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_prt_token_hash ON password_reset_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_prt_user_id ON password_reset_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_prt_expires ON password_reset_tokens (expires_at);

-- Retain the app_user references for existing drafts and audit entries.
ALTER TABLE timetable ADD COLUMN IF NOT EXISTS created_by_auth_user_id bigint REFERENCES users (id);
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS auth_user_id bigint REFERENCES users (id);

COMMIT;
